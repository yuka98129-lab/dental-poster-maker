// 医療広告で、誤解を招きやすい表現の「目安」のチェック。AI ではなく、決まった言葉の一覧で調べる(毎回同じ結果になる)。
// 最終的な確認は、医院でしてもらう。ここで見つからないことは、問題がないという意味ではない。

export type Finding = { word: string; hint: string };

const RULES: { re: RegExp; hint: string }[] = [
  { re: /痛くない|痛みがない|無痛/, hint: "「痛くない」「無痛」と言い切ると、誤解を招くおそれがあります。「痛みに配慮した」のような言い方が安心です。" },
  { re: /絶対|必ず|100[%％]|確実に|間違いなく/, hint: "効果や結果を保証するように読めます。「期待できます」「〜と言われています」などにすると安心です。" },
  { re: /日本一|地域一番|地域No\.?\s?1|ナンバーワン|No\.?\s?1|最高|最先端|最新鋭|他院より|どこよりも/, hint: "ほかと比べて優れていると読める表現は、避けるのが安全です。" },
  { re: /完治|治ります|治せます|治る/, hint: "治療の結果を言い切る表現は、避けたほうが安全です。" },
  { re: /安全です|副作用(は|が)ない|リスクなし|リスクはありません/, hint: "「安全」「リスクなし」と言い切ると、誤解を招くおそれがあります。" },
  { re: /ビフォー|アフター|症例写真|体験談|患者様の声|患者さんの声|口コミ/, hint: "ビフォーアフターや体験談は、医療広告では、原則として使えません。" },
  { re: /無料|割引|キャンペーン|円引き|お得/, hint: "料金や割引の案内は、条件(費用・期間など)を、きちんと書く必要がある場合があります。" },
  { re: /[○〇]{1,2}(月|日|時|分|円|回|歳)|○○/, hint: "「○」が残っています。日付や数字を入れてください。" },
];

/** 文章の中の、気をつけたい表現を、重複なしで返す */
export function checkText(...texts: string[]): Finding[] {
  const out: Finding[] = [];
  const seen = new Set<string>();
  for (const t of texts) {
    for (const rule of RULES) {
      const m = rule.re.exec(t);
      if (m && !seen.has(m[0])) {
        seen.add(m[0]);
        out.push({ word: m[0], hint: rule.hint });
      }
    }
  }
  return out;
}
